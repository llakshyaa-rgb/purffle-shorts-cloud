#!/data/data/com.termux/files/usr/bin/bash
# Install a local watchdog and optional Termux:Boot launch hook. Does not edit .env or credentials.
set -eu

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SERVICE="$ROOT/termux/purffle-service.sh"
BOOT_DIR="$HOME/.termux/boot"
BOOT_FILE="$BOOT_DIR/purffle.sh"

if [[ ! -f "$ROOT/purffle_shorts/__main__.py" ]]; then
    echo "Purffle package not found at $ROOT." >&2
    exit 1
fi

if ! command -v flock >/dev/null 2>&1; then
    echo "Installing util-linux (needed for safe single-instance locking)..."
    pkg install -y util-linux
fi

chmod +x "$SERVICE" "$ROOT/termux/install-service.sh"
mkdir -p "$BOOT_DIR"
cat > "$BOOT_FILE" <<EOF
#!/data/data/com.termux/files/usr/bin/bash
# Generated by Purffle's Termux installer.
export PURFFLE_ROOT="$ROOT"
"$SERVICE" start
EOF
chmod +x "$BOOT_FILE"

echo "Installed service helper: $SERVICE"
echo "Installed boot hook: $BOOT_FILE"
echo
echo "Starting Purffle now..."
"$SERVICE" start
echo
echo "For automatic startup after phone reboot:"
echo "1. Install the separate Termux:Boot app from the same trusted source as Termux."
echo "2. Open Termux:Boot once after installing it."
echo "3. Disable battery optimization for Termux in Android settings."
echo "4. Keep Termux's notification enabled; Android can still stop background work."
echo
echo "This installer does not change .env, turn uploads on, or run GitHub Actions."
